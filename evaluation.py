"""Explainable initial distance metric for two rare diseases.

This module consumes ``.data/features/diseases.parquet`` generated by
``generate_features.py``.  The metric is intentionally simple: each available
feature family produces a similarity in [0, 1], those similarities are combined
with configurable weights, and distance is ``1 - similarity``.

Missing feature families are omitted and the remaining weights are
renormalized.  An empty annotation list therefore means "unknown", not
"definitely absent".
"""

from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, Mapping, Optional, Sequence, Tuple

try:
    import pyarrow.parquet as pq
except ImportError:  # Keep --help available without the optional dependency.
    pq = None


PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_FEATURE_DIR = PROJECT_ROOT / ".data" / "features"

# These weights express an initial hypothesis, not learned clinical importance.
# Phenotypes and genes dominate; broad classifications provide supporting
# evidence; prevalence and approved treatments have lower weights because their
# coverage is less complete.
DEFAULT_WEIGHTS: Dict[str, float] = {
    "phenotypes": 0.35,
    "genes": 0.20,
    "classifications": 0.15,
    "body_systems": 0.10,
    "inheritance": 0.07,
    "onset": 0.05,
    "prevalence": 0.05,
    "approved_drugs": 0.03,
}

SET_FEATURES: Dict[str, str] = {
    "phenotypes": "hpo_ids",
    "genes": "gene_symbols",
    "classifications": "category_ids",
    "body_systems": "body_system_ids",
    "inheritance": "inheritance",
    "onset": "onset",
    "approved_drugs": "approved_drug_ids",
}

FEATURE_LABELS: Dict[str, str] = {
    "phenotypes": "HPO phenotypes",
    "genes": "associated genes",
    "classifications": "disease categories and ontology parents",
    "body_systems": "affected body systems",
    "inheritance": "inheritance patterns",
    "onset": "age-of-onset categories",
    "prevalence": "estimated prevalence",
    "approved_drugs": "approved drugs",
}

DISEASE_COLUMNS = [
    "orpha_id",
    "name",
    *SET_FEATURES.values(),
    "prevalence_estimated_per_person",
    "prevalence_class",
    "prevalence_region",
]


def normalize_orpha_id(value: str | int) -> str:
    """Normalize ``58``, ``ORPHA_58``, or ``ORPHA:58`` to ``ORPHA:58``."""

    match = re.fullmatch(r"\s*(?:(?:ORPHA|ORPHANET)\s*[:_-]?\s*)?(\d+)\s*", str(value), re.I)
    if not match:
        raise ValueError(
            f"Invalid disease ID {value!r}; expected an ORPHA ID such as ORPHA:58."
        )
    return f"ORPHA:{int(match.group(1))}"


def _clean_set(values: Optional[Iterable[Any]]) -> set[str]:
    """Convert an Arrow list value to a set of non-empty strings."""

    return {str(value) for value in values or [] if value not in (None, "")}


def _set_component(
    feature: str,
    values_a: Optional[Iterable[Any]],
    values_b: Optional[Iterable[Any]],
) -> Dict[str, Any]:
    """Calculate Jaccard similarity and overlap evidence for a set feature."""

    set_a = _clean_set(values_a)
    set_b = _clean_set(values_b)
    if not set_a or not set_b:
        return {
            "feature": feature,
            "label": FEATURE_LABELS[feature],
            "available": False,
            "reason": (
                "missing annotations for both diseases"
                if not set_a and not set_b
                else "missing annotations for one disease"
            ),
            "left_count": len(set_a),
            "right_count": len(set_b),
        }

    shared = sorted(set_a & set_b)
    union = set_a | set_b
    similarity = len(shared) / len(union)
    return {
        "feature": feature,
        "label": FEATURE_LABELS[feature],
        "available": True,
        "similarity": similarity,
        "distance": 1.0 - similarity,
        "shared_count": len(shared),
        "union_count": len(union),
        "left_count": len(set_a),
        "right_count": len(set_b),
        "shared": shared,
    }


def _prevalence_component(
    disease_a: Mapping[str, Any],
    disease_b: Mapping[str, Any],
) -> Dict[str, Any]:
    """Compare prevalence on a log scale.

    Similarity decays exponentially with the number of orders of magnitude
    separating the estimates.  A one-order difference has similarity e^-1.
    """

    prevalence_a = disease_a.get("prevalence_estimated_per_person")
    prevalence_b = disease_b.get("prevalence_estimated_per_person")
    if (
        prevalence_a is None
        or prevalence_b is None
        or float(prevalence_a) <= 0
        or float(prevalence_b) <= 0
    ):
        return {
            "feature": "prevalence",
            "label": FEATURE_LABELS["prevalence"],
            "available": False,
            "reason": "a comparable numeric prevalence estimate is unavailable",
            "left_value": prevalence_a,
            "right_value": prevalence_b,
        }

    log_difference = abs(math.log10(float(prevalence_a)) - math.log10(float(prevalence_b)))
    similarity = math.exp(-log_difference)
    return {
        "feature": "prevalence",
        "label": FEATURE_LABELS["prevalence"],
        "available": True,
        "similarity": similarity,
        "distance": 1.0 - similarity,
        "orders_of_magnitude_difference": log_difference,
        "left_value": float(prevalence_a),
        "right_value": float(prevalence_b),
        "left_class": disease_a.get("prevalence_class") or "",
        "right_class": disease_b.get("prevalence_class") or "",
        "left_region": disease_a.get("prevalence_region") or "",
        "right_region": disease_b.get("prevalence_region") or "",
    }


def _resolve_weights(overrides: Optional[Mapping[str, float]]) -> Dict[str, float]:
    """Merge and validate optional feature weight overrides."""

    weights = dict(DEFAULT_WEIGHTS)
    if overrides:
        unknown = sorted(set(overrides) - set(DEFAULT_WEIGHTS))
        if unknown:
            raise ValueError(
                "Unknown feature weight(s): "
                + ", ".join(unknown)
                + ". Valid features: "
                + ", ".join(DEFAULT_WEIGHTS)
            )
        weights.update({feature: float(weight) for feature, weight in overrides.items()})

    invalid = {
        feature: weight
        for feature, weight in weights.items()
        if not math.isfinite(weight) or weight < 0
    }
    if invalid:
        raise ValueError(f"Feature weights must be finite and non-negative: {invalid}")
    if not any(weight > 0 for weight in weights.values()):
        raise ValueError("At least one feature weight must be greater than zero.")
    return weights


class DiseaseDistanceEvaluator:
    """Load disease features once and evaluate any number of disease pairs."""

    def __init__(
        self,
        feature_dir: Path | str = DEFAULT_FEATURE_DIR,
        weights: Optional[Mapping[str, float]] = None,
    ) -> None:
        if pq is None:
            raise RuntimeError(
                "pyarrow is required for evaluation. Install it with "
                "`python -m pip install pyarrow`."
            )

        self.feature_dir = Path(feature_dir).expanduser().resolve()
        disease_path = self.feature_dir / "diseases.parquet"
        if not disease_path.is_file():
            raise FileNotFoundError(
                f"Feature file not found: {disease_path}. "
                "Run generate_features.py first."
            )

        self.weights = _resolve_weights(weights)
        table = pq.read_table(disease_path, columns=DISEASE_COLUMNS)
        self.diseases: Dict[str, Dict[str, Any]] = {
            str(row["orpha_id"]): row for row in table.to_pylist()
        }

    def get_disease(self, disease_id: str | int) -> Dict[str, Any]:
        """Return one disease row or raise an error with a useful message."""

        normalized = normalize_orpha_id(disease_id)
        try:
            return self.diseases[normalized]
        except KeyError as error:
            raise KeyError(
                f"{normalized} is not present in the generated feature cohort "
                f"({len(self.diseases):,} diseases)."
            ) from error

    def calculate_distance(
        self,
        disease_a_id: str | int,
        disease_b_id: str | int,
        weights: Optional[Mapping[str, float]] = None,
        *,
        allow_no_comparable: bool = False,
    ) -> Dict[str, Any]:
        """Calculate an explainable weighted distance between two diseases.

        The returned ``distance`` lies in [0, 1], where 0 means identical on all
        comparable selected features and 1 means no similarity.  The result also
        contains each component's overlap and effective normalized weight.  When
        ``allow_no_comparable`` is true, an annotation-free pair is returned with
        ``similarity`` and ``distance`` set to ``None`` instead of raising.
        """

        disease_a = self.get_disease(disease_a_id)
        disease_b = self.get_disease(disease_b_id)
        selected_weights = (
            _resolve_weights(weights) if weights is not None else dict(self.weights)
        )

        components = [
            _set_component(
                feature,
                disease_a.get(column),
                disease_b.get(column),
            )
            for feature, column in SET_FEATURES.items()
        ]
        components.append(_prevalence_component(disease_a, disease_b))

        available_weight = sum(
            selected_weights[component["feature"]]
            for component in components
            if component["available"]
            and selected_weights[component["feature"]] > 0
        )
        if available_weight <= 0 and not allow_no_comparable:
            raise ValueError(
                "The two diseases have no comparable features with a positive weight."
            )

        weighted_similarity = 0.0
        for component in components:
            configured_weight = selected_weights[component["feature"]]
            component["configured_weight"] = configured_weight
            if (
                available_weight > 0
                and component["available"]
                and configured_weight > 0
            ):
                effective_weight = configured_weight / available_weight
                component["effective_weight"] = effective_weight
                weighted_similarity += effective_weight * component["similarity"]
            else:
                component["effective_weight"] = 0.0

        if available_weight > 0:
            # Protect callers from insignificant floating-point overshoots.
            similarity: Optional[float] = min(
                1.0,
                max(0.0, weighted_similarity),
            )
            distance: Optional[float] = 1.0 - similarity
        else:
            similarity = None
            distance = None
        return {
            "disease_a": {
                "orpha_id": disease_a["orpha_id"],
                "name": disease_a["name"],
            },
            "disease_b": {
                "orpha_id": disease_b["orpha_id"],
                "name": disease_b["name"],
            },
            "distance": distance,
            "similarity": similarity,
            "comparable": available_weight > 0,
            "available_weight_before_normalization": available_weight,
            "configured_weights": selected_weights,
            "components": components,
            "interpretation": (
                "Heuristic initial metric; lower distance means greater similarity. "
                "It is not a clinical diagnosis or validated biological distance."
            ),
        }


def calculate_distance(
    disease_a_id: str | int,
    disease_b_id: str | int,
    feature_dir: Path | str = DEFAULT_FEATURE_DIR,
    weights: Optional[Mapping[str, float]] = None,
) -> Dict[str, Any]:
    """Convenience function for evaluating one disease pair.

    For many pairs, instantiate :class:`DiseaseDistanceEvaluator` once to avoid
    reloading the feature table.
    """

    evaluator = DiseaseDistanceEvaluator(feature_dir=feature_dir, weights=weights)
    return evaluator.calculate_distance(disease_a_id, disease_b_id)


def _parse_weight(value: str) -> Tuple[str, float]:
    """Parse ``FEATURE=WEIGHT`` CLI arguments."""

    if "=" not in value:
        raise argparse.ArgumentTypeError("expected FEATURE=WEIGHT")
    feature, raw_weight = value.split("=", 1)
    feature = feature.strip()
    try:
        weight = float(raw_weight)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"invalid weight {raw_weight!r}") from error
    if feature not in DEFAULT_WEIGHTS:
        raise argparse.ArgumentTypeError(
            f"unknown feature {feature!r}; choose from {', '.join(DEFAULT_WEIGHTS)}"
        )
    if not math.isfinite(weight) or weight < 0:
        raise argparse.ArgumentTypeError("weight must be finite and non-negative")
    return feature, weight


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(
        description=(
            "Calculate an explainable weighted distance between two diseases "
            "in the generated ORPHA feature set."
        )
    )
    parser.add_argument("disease_a", help="first ORPHA ID, for example ORPHA:98896")
    parser.add_argument("disease_b", help="second ORPHA ID, for example ORPHA:98895")
    parser.add_argument(
        "--feature-dir",
        type=Path,
        default=DEFAULT_FEATURE_DIR,
        help=f"generated feature directory (default: {DEFAULT_FEATURE_DIR})",
    )
    parser.add_argument(
        "--weight",
        action="append",
        type=_parse_weight,
        default=[],
        metavar="FEATURE=WEIGHT",
        help=(
            "override a default feature weight; may be repeated. Features: "
            + ", ".join(DEFAULT_WEIGHTS)
        ),
    )
    parser.add_argument(
        "--json",
        action="store_true",
        help="print the full result as JSON",
    )
    return parser.parse_args(argv)


def _format_result(result: Mapping[str, Any]) -> str:
    """Format a compact human-readable explanation."""

    disease_a = result["disease_a"]
    disease_b = result["disease_b"]
    lines = [
        (
            f"{disease_a['name']} ({disease_a['orpha_id']}) vs "
            f"{disease_b['name']} ({disease_b['orpha_id']})"
        ),
        f"Distance: {result['distance']:.4f}",
        f"Similarity: {result['similarity']:.4f}",
        "",
        "Feature contributions:",
    ]
    for component in result["components"]:
        if not component["available"]:
            lines.append(
                f"  - {component['label']}: unavailable ({component['reason']})"
            )
            continue
        contribution = (
            component["effective_weight"] * component["similarity"]
        )
        detail = ""
        if "shared_count" in component:
            detail = (
                f", shared {component['shared_count']} of "
                f"{component['union_count']}"
            )
            shared = component.get("shared", [])
            if shared:
                preview = ", ".join(shared[:8])
                if len(shared) > 8:
                    preview += ", ..."
                detail += f" [{preview}]"
        elif component["feature"] == "prevalence":
            detail = (
                ", log10 difference "
                f"{component['orders_of_magnitude_difference']:.3f}"
            )
        lines.append(
            f"  - {component['label']}: similarity "
            f"{component['similarity']:.4f}, effective weight "
            f"{component['effective_weight']:.1%}, contribution "
            f"{contribution:.4f}{detail}"
        )
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI entry point."""

    args = parse_args(argv)
    overrides = dict(args.weight)
    try:
        evaluator = DiseaseDistanceEvaluator(
            feature_dir=args.feature_dir,
            weights=overrides or None,
        )
        result = evaluator.calculate_distance(args.disease_a, args.disease_b)
    except (FileNotFoundError, KeyError, RuntimeError, ValueError, OSError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(_format_result(result))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
